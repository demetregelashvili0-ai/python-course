#შექმენი ცარიელი set, სახელად numbers. მომხმარებელს სთხოვე, შეიყვანოს 5 რიცხვი. თითოეული რიცხვი დაამატე Set-ში. 
# გამოიყენე while ციკლი, რათა მომხმარებელს რიცხვების შეყვანა მოსთხოვო მანამ, სანამ 5 რიცხვს არ შეიყვანს. ბოლოს დაბეჭდე Set.
numbers = set()

count = 0

while count < 5:
    num = int(input("შეიყვანე რიცხვი: "))
    numbers.add(num)
    count += 1

print(numbers)