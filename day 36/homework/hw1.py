#  რომლებიც 5-ზე იყოფა უნაშთოდ. შემდეგ ეს რიცხვები დაამატე ცალკე set-ში და დაბეჭდე მიღებული Set.
numbers = [5, 12, 8, 15, 20, 3, 12, 25, 7, 15]

