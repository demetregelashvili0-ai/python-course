#შექმენით მაღაზიის Dictionary, რომელშიც შეინახავთ 5 პროდუქტის სახელსა და ფასს.
#  მომხმარებელს შემოაყვანინეთ ახალი პროდუქტების სახელები და ფასები და დაამატეთ ისინი არსებულ ობიექტში. საბოლოოდ დაბეჭდეთ განახლებული Dictionary.


shop = {
    "პური": 2,
    "რძე": 4,
    "კვერცხი": 6,
    "ვაშლი": 3,
    "წყალი": 1
}

for i in range(2):
    product = input("შეიყვანეთ პროდუქტის სახელი: ")
    price = int(input("შეიყვანეთ პროდუქტის ფასი: "))
    shop.update({product: price})

print(f"განახლებული Dictionary: {shop}")
