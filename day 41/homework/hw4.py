menu = {
    "ხინკალი": 2,
    "ხაჭაპური": 20,
    "მწვადი": 25,
    "ლობიანი": 12,
    "სალათი": 10,
    "კარტოფილი": 8
}

for x in menu:
    print(x, menu[x])

name = ""
price = 0

for x in menu:
    if menu[x] > price:
        price = menu[x]
        name = x

print("ყველაზე ძვირია:", name, price)