#შექმენით ბიბლიოთეკის Dictionary, რომელშიც შეინახავთ 5 წიგნის სახელსა და მათ გვერდების რაოდენობას. მომხმარებელს შემოაყვანინეთ 
# წიგნის სახელი და მოძებნეთ მისი გვერდების რაოდენობა. თუ წიგნი არ არსებობს, გამოიტანეთ შესაბამისი შეტყობინება. ბოლოს დაბეჭდეთ ყველა წიგნის სახელი.
library = {
    "ვეფხისტყაოსანი": 300,
    "ჰარი პოტერი": 400,
    "პატარა უფლისწული": 120,
    "შერლოკ ჰოლმსი": 250,
    "დათა თუთაშხია": 450
}

name = input("შეიყვანე წიგნის სახელი: ")

if name in library:
    print(library[name], "გვერდი")
else:
    print("ასეთი წიგნი არ მოიძებნა")

print("ყველა წიგნი:")
for book in library.keys():
    print(book)