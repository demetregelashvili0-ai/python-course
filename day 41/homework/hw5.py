students = {
    "გიორგი": 80,
    "ნიკა": 40,
    "ანა": 90,
    "ლუკა": 30,
    "მარიამი": 60
}

count = 0

for x in students:
    print(x, students[x])

    if students[x] > 50:
        print("ჩააბარა")
        count += 1
    else:
        print("ვერ ჩააბარა")

print("ჩაბარებული სტუდენტების რაოდენობა:", count)