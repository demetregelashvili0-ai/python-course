#10) მომხმარებელს შეაყვანინეთ რიცხვები. თუ მომხმარებელი შეიყვანს 10 ზე დაბალ რიცხვს, გამოიყენეთ break და თუ 10 ზე მეტს დაამატე total ცვლადში და ბოლოს გამოიტანეთ ჯამი.

total = 0

while True:
     num1 = int(input("enter a number"))
     if num1 < 10:
          break

     total += num1
print("10ზე მეტია ან  ტოლი რიცხვების ჯამი არის", total)