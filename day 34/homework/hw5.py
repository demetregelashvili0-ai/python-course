#5) შექმენი ორი Set სახელად `available_books` და `new_books`. პირველში შეინახე ბიბლიოთეკაში არსებული 6 წიგნის სახელი, ხოლო მეორეში — 4 ახალი წიგნის სახელი. 
# ზოგიერთი წიგნი ორივე Set-ში უნდა გვხვდებოდეს. თავდაპირველად გამოიყენე `intersection()` მეთოდი, რათა გაიგო, რომელი ახალი წიგნები უკვე არსებობს ბიბლიოთეკაში.
#  შემდეგ გამოიყენე `union()` მეთოდი, რათა მიიღო ბიბლიოთეკის განახლებული წიგნების სია. დაბეჭდე ორივე შედეგი და საბოლოო წიგნების რაოდენობა.
available_books = {"ვეფხისტყაოსანი","ჰარი პოტერი","დიდოსტატის მარჯვენა","პატარა უფლისწული","ოთარაანთ ქვრივი","კაცია-ადამიანი?!"}

new_books = {"ჰარი პოტერი","პატარა უფლისწული","ალქიმიკოსი","ტომ სოიერის თავგადასავალი"}
books = available_books.intersection(new_books)
all_books= available_books.union(new_books)
print(books)
print(all_books)
print(len(all_books))